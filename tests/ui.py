import asyncio, sys
from playwright.async_api import async_playwright

BASE = "http://localhost:8080"
OUT = __import__("os").path.join(__import__("os").path.dirname(__import__("os").path.abspath(__file__)), "shots"); __import__("os").makedirs(OUT, exist_ok=True)
errors = []

async def pin(page, code):
    for d in code:
        await page.click(f'button[data-k="{d}"]')
    await page.wait_for_selector("aside.side", timeout=5000)

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path=__import__("os").environ.get("CHROME","/usr/bin/google-chrome"), args=["--no-sandbox"])
        ctx = await b.new_context(viewport={"width": 1366, "height": 820})
        page = await ctx.new_page()
        page.on("console", lambda m: m.type == "error" and errors.append("kassir: " + m.text))
        page.on("pageerror", lambda e: errors.append("kassir pageerror: " + str(e)))
        await page.goto(BASE)
        await page.screenshot(path=f"{OUT}/01-login.png")
        await pin(page, "2222")
        # smena ochish
        await page.click('button[data-v="cash"]')
        await page.fill("#open-cash", "200000")
        await page.click('[data-a="openShift"]')
        await page.wait_for_timeout(400)
        await page.click('nav.snav button[data-v="floor"]')
        await page.click('.table >> nth=0')
        await page.click('.modal [data-v="3"]')
        await page.wait_for_selector("#products .product")
        prods = page.locator("#products .product")
        await prods.nth(0).click(); await page.wait_for_timeout(150)
        await prods.nth(0).click(); await page.wait_for_timeout(150)
        await prods.nth(1).click(); await page.wait_for_timeout(150)
        # modifikator bilan
        await page.click('#products .product >> nth=2 >> .more')
        await page.click('.modal [data-m="toggle"] >> nth=0')
        await page.fill('.modal input[name="comment"]', "tezroq")
        await page.click('.modal [data-m="ok"]')
        await page.wait_for_timeout(300)
        await page.click('#cats button >> nth=4')
        await page.click('#products .product >> nth=0')
        await page.wait_for_timeout(300)
        await page.screenshot(path=f"{OUT}/02-order-new.png")
        await page.click('[data-a="send"]')
        await page.wait_for_timeout(500)
        await page.screenshot(path=f"{OUT}/03-order-sent.png")

        # Oshpaz alohida qurilmada
        ctx2 = await b.new_context(viewport={"width": 1280, "height": 800})
        cook = await ctx2.new_page()
        cook.on("console", lambda m: m.type == "error" and errors.append("oshpaz: " + m.text))
        cook.on("pageerror", lambda e: errors.append("oshpaz pageerror: " + str(e)))
        await cook.goto(BASE)
        await pin(cook, "4444")
        await cook.wait_for_selector(".kcard")
        await cook.screenshot(path=f"{OUT}/04-kitchen.png")
        await cook.click('[data-a="kall"] >> nth=0')
        await cook.wait_for_timeout(600)
        await cook.click('[data-a="kall"] >> nth=0')
        await cook.wait_for_timeout(800)
        await cook.screenshot(path=f"{OUT}/05-kitchen-ready.png")

        # Kassirda real-time "tayyor" ko'rinishi kerak
        await page.wait_for_timeout(600)
        await page.screenshot(path=f"{OUT}/06-order-ready-realtime.png")
        await page.click('nav.snav button[data-v="floor"]')
        await page.wait_for_timeout(300)
        await page.screenshot(path=f"{OUT}/07-floor.png")
        await page.click('.table >> nth=0')
        await page.wait_for_selector('[data-a="pay"]')
        await page.click('[data-a="pay"]')
        await page.click('.modal [data-q="+200000"]')
        await page.wait_for_timeout(200)
        await page.screenshot(path=f"{OUT}/08-pay.png")
        await page.click('#pay-ok')
        await page.wait_for_selector('.modal h2:has-text("qabul qilindi")')
        await page.screenshot(path=f"{OUT}/09-paid.png")
        await page.click('.modal [data-m="close"]')
        await page.click('nav.snav button[data-v="cash"]')
        await page.wait_for_selector(".grid-stats")
        await page.screenshot(path=f"{OUT}/10-cash.png", full_page=True)

        # Admin
        ctx3 = await b.new_context(viewport={"width": 1366, "height": 820})
        adm = await ctx3.new_page()
        adm.on("console", lambda m: m.type == "error" and errors.append("admin: " + m.text))
        adm.on("pageerror", lambda e: errors.append("admin pageerror: " + str(e)))
        await adm.goto(BASE)
        await pin(adm, "1111")
        await adm.click('nav.snav button[data-v="admin"]')
        await adm.wait_for_selector("table.list")
        await adm.screenshot(path=f"{OUT}/11-admin-menu.png")
        await adm.click('[data-a="aedit"] >> nth=1')
        await adm.fill('.modal input[name="price"]', "37000")
        await adm.click('.modal [data-m="ok"]')
        await adm.wait_for_timeout(400)
        await adm.click('[data-v="audit"]')
        await adm.wait_for_selector("table.list")
        await adm.screenshot(path=f"{OUT}/12-audit.png")

        # Telefon: ofitsiant
        ctx4 = await b.new_context(viewport={"width": 390, "height": 844}, is_mobile=True, has_touch=True)
        ph = await ctx4.new_page()
        ph.on("pageerror", lambda e: errors.append("telefon pageerror: " + str(e)))
        await ph.goto(BASE)
        await pin(ph, "3333")
        await ph.screenshot(path=f"{OUT}/13-phone-floor.png")
        await ph.click('.table >> nth=2')
        await ph.click('.modal [data-v="2"]')
        await ph.wait_for_selector("#products .product")
        await ph.click('#products .product >> nth=0')
        await ph.wait_for_timeout(300)
        await ph.screenshot(path=f"{OUT}/14-phone-menu.png")
        await ph.click('[data-a="pane"][data-v="ticket"]')
        await ph.wait_for_timeout(200)
        await ph.screenshot(path=f"{OUT}/15-phone-ticket.png")
        await b.close()
    print("ERRORS:", errors if errors else "yo'q")

asyncio.run(main())
